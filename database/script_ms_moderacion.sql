BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE REPORTE CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE REPORTE (
    ID_REPORTE     NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TIPO_CONTENIDO VARCHAR2(20 CHAR)  NOT NULL,
    ID_CONTENIDO   NUMBER(19)         NOT NULL,
    MOTIVO         VARCHAR2(500 CHAR) NOT NULL,
    ID_USUARIO     NUMBER(19)         NOT NULL,
    AUTOR_REPORTE  VARCHAR2(30 CHAR)  NOT NULL,
    ESTADO         VARCHAR2(20 CHAR)  DEFAULT 'PENDIENTE' NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_REPORTE PRIMARY KEY (ID_REPORTE),
    CONSTRAINT CK_REPORTE_TIPO_CONTENIDO CHECK (TIPO_CONTENIDO IN ('TEMA', 'COMENTARIO')),
    CONSTRAINT CK_REPORTE_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'RESUELTO', 'DESCARTADO'))
);

CREATE TABLE SANCION (
    ID_SANCION       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TIPO_CONTENIDO   VARCHAR2(20 CHAR)  NOT NULL,
    ID_CONTENIDO     NUMBER(19)         NOT NULL,
    TIPO_SANCION     VARCHAR2(20 CHAR)  NOT NULL,
    MOTIVO           VARCHAR2(500 CHAR) NOT NULL,
    MODERADOR        VARCHAR2(30 CHAR)  NOT NULL,
    ACTIVA           NUMBER(1) DEFAULT 1 NOT NULL,
    FECHA_CREACION   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_REVOCACION TIMESTAMP,
    ID_REPORTE       NUMBER(19),
    CONSTRAINT PK_SANCION PRIMARY KEY (ID_SANCION),
    CONSTRAINT CK_SANCION_TIPO_CONTENIDO CHECK (TIPO_CONTENIDO IN ('TEMA', 'COMENTARIO')),
    CONSTRAINT CK_SANCION_TIPO CHECK (TIPO_SANCION IN ('OCULTAR', 'ADVERTENCIA', 'ELIMINAR')),
    CONSTRAINT CK_SANCION_ACTIVA CHECK (ACTIVA IN (0, 1)),
    CONSTRAINT CK_SANCION_REVOCACION CHECK ((ACTIVA = 1 AND FECHA_REVOCACION IS NULL)
                                         OR (ACTIVA = 0 AND FECHA_REVOCACION IS NOT NULL)),
    CONSTRAINT FK_SANCION_REPORTE FOREIGN KEY (ID_REPORTE) REFERENCES REPORTE (ID_REPORTE)
);

CREATE INDEX IX_REPORTE_CONTENIDO ON REPORTE (TIPO_CONTENIDO, ID_CONTENIDO);
CREATE INDEX IX_SANCION_CONTENIDO ON SANCION (TIPO_CONTENIDO, ID_CONTENIDO);
CREATE INDEX IX_SANCION_REPORTE ON SANCION (ID_REPORTE);

