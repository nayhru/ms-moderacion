CREATE TABLE EJEMPLO (
    ID_EJEMPLO     NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE         VARCHAR2(60 CHAR)  NOT NULL,
    DESCRIPCION    VARCHAR2(200 CHAR),
    ID_USUARIO     NUMBER(19)         NOT NULL,
    AUTOR          VARCHAR2(30 CHAR)  NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EJEMPLO PRIMARY KEY (ID_EJEMPLO),
    CONSTRAINT UQ_EJEMPLO_NOMBRE UNIQUE (NOMBRE)
);

